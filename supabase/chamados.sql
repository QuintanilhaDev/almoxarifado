--  Max Hub · Chamados para o desenvolvedor
--
--  Cole TODO este arquivo no SQL Editor do Supabase e clique em "Run".
--  Pode rodar a qualquer momento (não depende de outros arquivos além do
--  básico do Max Hub).
--
--  Cria a tabela de chamados: qualquer pessoa de qualquer setor abre um
--  chamado (erro, melhoria, dúvida); só o desenvolvedor responde.
--  A conversa fica em "messages" (lista de mensagens com data, autor e anexos).
--
--  NÃO apaga nada. Pode rodar mais de uma vez (é idempotente).
-- =====================================================================

create table if not exists public.tickets (
  id              uuid primary key default gen_random_uuid(),
  number          integer generated by default as identity unique,
  sector          text,
  opened_by_id    uuid,
  opened_by       text not null,
  opened_by_user  text,
  title           text not null check (length(btrim(title)) between 1 and 140),
  kind            text not null default 'erro' check (kind in ('erro', 'melhoria', 'duvida', 'outro')),
  priority        text not null default 'normal' check (priority in ('baixa', 'normal', 'alta', 'urgente')),
  status          text not null default 'aberto' check (status in ('aberto', 'em_andamento', 'respondido', 'resolvido', 'fechado')),
  -- tela em que a pessoa estava quando abriu (ajuda a achar o problema)
  page            text,
  -- [{ at, by, dev, text, attachments: [{ path, name, size, type }] }]
  messages        jsonb not null default '[]'::jsonb,
  -- quem falou por último: 'usuario' ou 'dev' (para os avisos de "nova resposta")
  last_from       text not null default 'usuario' check (last_from in ('usuario', 'dev')),
  -- quando quem abriu viu a última resposta do desenvolvedor
  owner_seen_at   timestamptz,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  resolved_at     timestamptz
);

create index if not exists tickets_opened_by_id_idx on public.tickets (opened_by_id);
create index if not exists tickets_status_idx on public.tickets (status, updated_at desc);

alter table public.tickets enable row level security;
grant all on public.tickets to service_role;
