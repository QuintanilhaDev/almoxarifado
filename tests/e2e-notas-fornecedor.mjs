/** Digitar nota fiscal (Almoxarifado): a caixa do fornecedor sugere o cadastro de Compras. */
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PW || 'playwright');
const B = 'http://localhost:3100', O = process.env.SHOTS || '/tmp/shots';
const problems = [];
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1360, height: 900 } })).newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
const ok = (c, m) => { if (!c) problems.push(m); console.log(c ? '  ✓' : '  ✗', m); };
await p.goto(B + '/'); await p.fill('#user', 'mateus'); await p.fill('#pass', '123456'); await p.click('button[type=submit]');
await p.waitForURL('**/hub');
const post = (body) => p.evaluate(async (bd) => (await fetch('/api/compras/fornecedores', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(bd) })).status, body);
ok((await Promise.all([post({ name: 'Malharia Bahia Ltda', trade_name: 'Malharia Bahia', cnpj: '11222333000181', category: 'Fardamento' }), post({ name: 'Botas Forte Comércio', category: 'Botas e calçados' })])).every((x) => x === 200), 'dois fornecedores cadastrados em Compras');
await p.goto(B + '/setor/almoxarifado#notas'); await p.waitForSelector('[data-max="nota-digitar"]'); await p.waitForTimeout(1200);
await p.click('[data-max="nota-digitar"]'); await p.waitForSelector('#n-sup');
await p.click('#n-sup'); await p.waitForTimeout(300);
ok(await p.locator('.sp-opt').count() === 2, 'ao clicar, mostra os fornecedores do cadastro');
await p.fill('#n-sup', 'malh'); await p.waitForTimeout(200);
ok(await p.locator('.sp-opt').count() === 1 && /Malharia Bahia/.test(await p.locator('.sp-opt').first().textContent()), 'digitando "malh": sugere a Malharia');
await p.screenshot({ path: O + '/sp1.png', clip: { x: 300, y: 80, width: 800, height: 420 } });
await p.keyboard.press('Enter');
ok((await p.inputValue('#n-sup')) === 'Malharia Bahia Ltda' && (await p.inputValue('#n-cnpj')) === '11.222.333/0001-81', 'Enter escolhe: nome e CNPJ preenchidos');
ok(await p.locator('.sp-list').count() === 0 && await p.locator('.modal').count() === 1, 'lista fecha e o formulário continua aberto');
await p.fill('#n-sup', 'calçados'); await p.waitForTimeout(200);
ok(/Botas Forte/.test(await p.locator('.sp-opt').first().textContent()), 'busca também pelo que o fornecedor vende');
await p.fill('#n-sup', 'Fornecedor Novo XYZ'); await p.waitForTimeout(200);
ok(await p.locator('.sp-hint').count() === 1, 'nome fora do cadastro: avisa que entra quando a nota for lançada');
await p.keyboard.press('Escape'); await p.waitForTimeout(200);
ok(await p.locator('.modal').count() === 1 && await p.locator('.sp-list').count() === 0, 'Esc fecha só a lista, não o formulário');
await b.close();
problems.push(...errs);
console.log(problems.length ? '\n' + problems.length + ' problema(s):\n- ' + problems.join('\n- ') : '\nTUDO CERTO');
process.exit(problems.length ? 1 : 0);
